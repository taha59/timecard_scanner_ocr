const assert=require('node:assert/strict'),vm=require('node:vm');
const {buildSync}=require('../frontend/node_modules/esbuild');
const clock=[180,185],context={performance:{now:()=>clock.shift()}};vm.createContext(context);
vm.runInContext(buildSync({entryPoints:['frontend/src/scan-timing.tsx'],bundle:true,write:false,format:'iife',globalName:'scanTiming',jsx:'automatic'}).outputFiles[0].text,context);
const {parseServerTiming,readTimedJson}=context.scanTiming;
assert.deepEqual(JSON.parse(JSON.stringify(parseServerTiming(null))),{});
assert.deepEqual(JSON.parse(JSON.stringify(parseServerTiming('compute;dur=1234.5, handler;dur=1500'))),{compute:1234.5,handler:1500});
assert.deepEqual(JSON.parse(JSON.stringify(parseServerTiming('bad;dur=Infinity, bad2;dur=-20'))),{});
(async()=>{
 const headers={'Server-Timing':'request_read;dur=10, compute;dur=25','X-Response-Bytes':'1234'};
 const result=await readTimedJson({text:async()=>'{"layouts":[],"tasks":[]}',headers:{get:name=>headers[name]??null}},100,150);
 assert.deepEqual(JSON.parse(JSON.stringify(result.data)),{layouts:[],tasks:[]});
 assert.equal(result.timing.untilResponseMs,50);
 assert.equal(result.timing.downloadMs,30);
 assert.equal(result.timing.jsonParseMs,5);
 assert.equal(result.timing.responseBytes,1234);
 assert.equal(result.timing.server.compute,25);
 const {renderToStaticMarkup}=require('../frontend/node_modules/react-dom/server');
 const html=renderToStaticMarkup(context.scanTiming.PreparationTiming({timing:result.timing}));
 assert.ok(html.includes('Preparation breakdown'));
 assert.ok(html.includes('Server processing'));
 assert.ok(html.includes('Parse JSON on this device'));
 assert.ok(html.includes('not extra time'));
 assert.ok(html.includes('Not available'));
 const reading=renderToStaticMarkup(context.scanTiming.ReadingTiming({stats:{inferenceMs:20,imageDecodeMs:5,inputPrepMs:2,textDecodeMs:3,cleanupMs:1,otherMs:0}}));
 assert.ok(reading.includes('Reading breakdown')&&reading.includes('Model inference'));
 assert.equal(context.scanTiming.ReadingTiming({stats:{readMs:100}}),null);
 const results=renderToStaticMarkup(context.scanTiming.ResultsTiming({timing:result.timing}));
 assert.ok(results.includes('Results check breakdown')&&results.includes('Results server processing')); 
 assert.equal(result.timing.untilResponseMs+result.timing.downloadMs+result.timing.jsonParseMs,85);
 clock.push(200,201);
 const old=await readTimedJson({text:async()=>'{}',headers:{get:()=>null}},185,190);
 assert.equal(old.timing.responseBytes,null);
 assert.deepEqual(JSON.parse(JSON.stringify(old.timing.server)),{});
 clock.push(220);await assert.rejects(readTimedJson({text:async()=>'<bad>',headers:{get:()=>null}},201,205));
 console.log('PASS: preparation timings separate response wait, body download and JSON parsing; server timings remain separate and missing headers are supported.');
})().catch(e=>{console.error(e);process.exitCode=1;});
