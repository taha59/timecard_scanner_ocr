const assert=require('node:assert/strict'),vm=require('node:vm');
const {buildSync}=require('../frontend/node_modules/esbuild');
const context={};vm.createContext(context);
vm.runInContext(buildSync({entryPoints:['frontend/src/ocr-policy.ts'],bundle:true,write:false,format:'iife',globalName:'policy'}).outputFiles[0].text,context);
const {clearClock,skipFallback}=context.policy;
const good={text:'10:25 AM',confidence:.79,quality:.97};
assert.equal(clearClock(good),true);
for(const text of ['24:00','9:65','0:30pm','13:00am','9:0','9:OOAM','9:00AM total','OFF'])assert.equal(clearClock({...good,text}),false,text);
assert.equal(clearClock({...good,quality:.89}),false);
assert.equal(clearClock({...good,quality:NaN}),false);
assert.equal(clearClock({...good,quality:undefined}),false);
assert.equal(skipFallback({id:'fallback',image:'',required:false,fallback_for:['a']},{a:good}),true);
assert.equal(skipFallback({id:'fallback',image:'',required:true,fallback_for:['a']},{a:good}),false);
assert.equal(skipFallback({id:'fallback',image:'',fallback_for:['a']},{a:good}),false);
assert.equal(skipFallback({id:'fallback',image:'',required:false,fallback_for:['a','b']},{a:good}),false);
assert.equal(skipFallback({id:'a',image:'',required:false,fallback_for:['a']},{a:good}),false);
console.log('PASS: only high-quality, valid original clocks allow dependent fallback crops to be skipped; ambiguous, missing, primary and shared-required readings remain checked.');
const {readableClock,cropStage}=context.policy;
assert.equal(readableClock({text:'10:35pm',confidence:.1}),true);
assert.equal(readableClock({text:'11:400 1',confidence:.99}),false);
assert.equal(readableClock({text:'10:20 5:00',confidence:.99}),false);
const recovery={id:'focus',image:'',required:false,recover_for:[['a','b']]};
assert.equal(skipFallback(recovery,{a:{text:'10:35pm',confidence:.1}}),true);
assert.equal(skipFallback(recovery,{a:{text:'not readable',confidence:.99}}),false);
assert.equal(skipFallback({...recovery,recover_for:[['a','b'],['c','d']]},{a:good}),false);
assert.equal(cropStage({id:'x',image:'',required:true}),0);
assert.equal(cropStage(recovery),2);
console.log('PASS: missing-field recovery retries ignore confidence, run after ordinary crops, and cannot skip an unresolved/shared field.');
const edgeRecovery={...recovery,edge_recovery:true};
assert.equal(skipFallback(edgeRecovery,{a:{text:'1:45pm',confidence:.99}}),false);
assert.equal(skipFallback(edgeRecovery,{a:{text:'2:00pm',confidence:.99}}),false);
assert.equal(skipFallback(edgeRecovery,{a:{text:'11:45pm',confidence:.1}}),true);
assert.equal(skipFallback(edgeRecovery,{a:{text:'0:55pm',confidence:.99}}),false);
assert.equal(cropStage(edgeRecovery),3);
console.log('PASS: label-edge crops also check potentially clipped leading digits after normal recovery.');
assert.equal(skipFallback(edgeRecovery,{a:{text:'0:45',confidence:.99}}),false);
